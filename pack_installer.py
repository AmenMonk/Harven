def md5_of(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_zip_name(zip_path: Path):
    """HarvenAI_v0.3.2_lite_Windows_20261104_r45.zip -> (0.3.2, lite, r45)"""
    m = re.match(r"HarvenAI_v([\d.]+)_(\w+)_Windows_\d{8}_(r\d+)\.zip$", zip_path.name)
    if not m:
        sys.exit(f"[FAIL] zip filename not recognized: {zip_path.name}")
    return m.group(1), m.group(2), m.group(3)


def extract_zip(zip_path: Path, dest: Path):
    print(f"[1/5] Extracting {zip_path.name} -> {dest}")
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    with zipfile.ZipFile(zip_path) as z:
        total = len(z.infolist())
        for i, info in enumerate(z.infolist(), 1):
            z.extract(info, dest)
            if i % 200 == 0 or i == total:
                print(f"      {i}/{total}")
    # non-ASCII name sanity: the launcher bat must exist with its Chinese name
    for req in REQUIRED_IN_ZIP:
        if not (dest / req).exists():
            sys.exit(f"[FAIL] required file missing after extract: {req}")
    print(f"      all {len(REQUIRED_IN_ZIP)} required files present")


def inject_silent_bat(dest: Path):
    print("[2/5] Injecting silent_install.bat")
    if not SILENT_BAT_SRC.exists():
        sys.exit(f"[FAIL] source not found: {SILENT_BAT_SRC}")
    got = md5_of(SILENT_BAT_SRC)
    if got != SILENT_BAT_MD5:
        sys.exit(f"[FAIL] silent_install.bat MD5 mismatch: {got} != {SILENT_BAT_MD5}")
    shutil.copy2(SILENT_BAT_SRC, dest / "silent_install.bat")
    print(f"      injected (MD5 {got})")


def write_iss(dest: Path, version: str, tier: str, rev: str, out_dir: Path, exe_name: str) -> Path:
    print("[3/5] Generating .iss")
    # ★ #1426 实锤：full 档加 219MB wheel 后安装器总量超 Windows 单 exe 4.2GB 上限
    #   （r46 full 4.17GB 压线，r47 4.38GB 必炸「Disk spanning must be enabled」）。
    #   full 档开 DiskSpanning -> exe(首卷) + -1.bin/-2.bin 分卷（用户放同目录双击 exe 即装）；
    #   lite/standard 维持单文件形态。
    if tier == "full":
        disk_slice_lines = (
            "DiskSpanning=yes\n"
            "SlicesPerDisk=1\n"
            "DiskSliceSize=2100000000"
        )
    else:
        disk_slice_lines = "DiskSliceSize=2147483647"
    body = ISS_TEMPLATE.format(
        build_dir=str(dest),
        version=version,
        rev=rev,
        tier=tier,
        app_id=APP_ID,
        out_dir=str(out_dir),
        exe_name=exe_name,
        tier_hint=TIER_HINTS[tier],
        disk_slice_lines=disk_slice_lines,
    )
    iss = dest / "installer.iss"
    # UTF-8 with BOM so Inno Setup reads the Chinese strings correctly
    iss.write_text(body, encoding="utf-8-sig")
    print(f"      {iss}")
    return iss


def compile_iss(iss: Path):
    print("[4/5] Compiling with ISCC (this streams the full payload, be patient)...")
    r = subprocess.run([str(ISCC), "/Qp", str(iss)], capture_output=True, text=True,
                       errors="replace", cwd=str(iss.parent))
    if r.returncode != 0:
        print("--- ISCC stdout ---")
        print(r.stdout[-4000:])
        print("--- ISCC stderr ---")
        print(r.stderr[-4000:])
        sys.exit(f"[FAIL] ISCC exited {r.returncode}")
    # note: /Qp silences progress AND the "Successful compile" banner,
    # so success is judged by exit code + output exe existence (checked in main)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", required=True)
    ap.add_argument("--out-dir", default=r"C:\Users\usera\Desktop")
    ap.add_argument("--keep", action="store_true", help="keep the temp build dir for debugging")
    args = ap.parse_args()

    zip_path = Path(args.zip)
    if not zip_path.exists():
        sys.exit(f"[FAIL] zip not found: {zip_path}")
    if not ISCC.exists():
        sys.exit(f"[FAIL] ISCC not found: {ISCC}")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    version, tier, rev = parse_zip_name(zip_path)
    exe_name = f"哈文AI安装器_v{version}_{tier}_{rev}"
    print(f"=== HarvenAI installer build: v{version} / {tier} / {rev} ===")

    build_dir = BUILD_ROOT / tier
    extract_zip(zip_path, build_dir)
    inject_silent_bat(build_dir)
    iss = write_iss(build_dir, version, tier, rev, out_dir, exe_name)
    compile_iss(iss)

    exe_path = out_dir / f"{exe_name}.exe"
    if not exe_path.exists():
        sys.exit("[FAIL] exe not produced")
    size_mb = exe_path.stat().st_size / 1024 / 1024
    digest = md5_of(exe_path)

    if args.keep:
        print(f"[5/5] Build dir kept for debug: {build_dir}")
    else:
        print("[5/5] Cleaning build dir")
        shutil.rmtree(build_dir, ignore_errors=True)

    print()
    print("=" * 62)
    print(f"  DONE  {exe_path.name}")
    print(f"  size  {size_mb:.1f} MB")
    print(f"  MD5   {digest}")
    print("=" * 62)


if __name__ == "__main__":
    main()
