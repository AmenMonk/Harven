class SkillBuilder:
    """Skill 制作向导引擎"""

    def __init__(self):
        self._ensure_skills_dir()

    def _ensure_skills_dir(self):
        SKILLS_DIR.mkdir(parents=True, exist_ok=True)

    def detect_skill_category(self, description: str) -> str:
        """根据用户描述自动检测 Skill 类别"""
        desc_lower = description.lower()
        category_keywords = {
            "web_search": ["搜索", "查询", "网络", "新闻", "资讯", "信息", "search", "query"],
            "weather": ["天气", "气温", "温度", "气候", "weather", "下雨"],
            "calculator": ["计算", "运算", "数学", "算", "calc", "math"],
            "file_ops": ["文件", "读写", "目录", "保存", "file", "read", "write"],
            "translation": ["翻译", "translate", "语言", "中译", "英译"],
            "time_date": ["时间", "日期", "几点", "星期", "time", "date", "clock"],
            "intermediate": ["记账", "记录", "跟踪", "管理", "统计", "汇总", "监控", "定时", "提醒",
                             "数据库", "存储", "持久化", "自动", "定期", "习惯", "日志", "打卡"],
        }
        scores = {}
        for cat, keywords in category_keywords.items():
            scores[cat] = sum(1 for kw in keywords if kw in desc_lower)
        best = max(scores, key=scores.get, default="custom")
        return best if scores.get(best, 0) > 0 else "custom"

    def generate_skill_code(self, name: str, description: str,
                            category: str = None,
                            extra_info: str = "",
                            skill_id: str = None) -> str:
        """
        根据描述生成完整的 Skill Python 代码

        Args:
            name: Skill 名称
            description: 功能描述
            category: 类别（auto-detect 留空）
            extra_info: 额外信息（如特定 API、参数说明）
            skill_id: 自定义 ID（不传则自动生成）

        Returns:
            str: 完整的 Python 代码（中级Skill返回空字符串，请用 generate_intermediate_skill）
        """
        if not category:
            category = self.detect_skill_category(description)

        # ★ 2026-07-14: 中级Skill走独立生成通道
        if category == "intermediate":
            return ""  # 调用方应使用 generate_intermediate_skill()

        template = SKILL_CATEGORY_TEMPLATES.get(category, SKILL_CATEGORY_TEMPLATES["custom"])

        if not skill_id:
            skill_id = f"skill_{uuid.uuid4().hex[:8]}"

        # 生成触发词：从描述和名称中提取
        triggers = self._extract_triggers(name, description, template.get("triggers", []))

        # 生成代码
        code = SKILL_TEMPLATE.format(
            skill_id=skill_id,
            name=name,
            version="1.0.0",
            description=description,
            triggers=json.dumps(triggers, ensure_ascii=False),
            priority=5,
            function_doc=template.get("description", description),
            body=template.get("body", "        pass"),
        )

        return code

    def _extract_triggers(self, name: str, description: str, default_triggers: List[str]) -> List[str]:
        """从名称和描述中提取触发词"""
        triggers = set(default_triggers)
        # 从名称中提取关键词
        name_words = re.findall(r'[\u4e00-\u9fff\w]+', name)
        triggers.update([w.strip().lower() for w in name_words if len(w.strip()) >= 2])
        # 从描述中提取关键词
        desc_words = re.findall(r'[\u4e00-\u9fff\w]+', description)
        triggers.update([w.strip().lower() for w in desc_words[:5] if len(w.strip()) >= 2])
        return sorted(triggers)[:15]

    def validate_skill_code(self, code: str) -> Tuple[bool, str]:
        """验证生成的 Skill 代码是否合法"""
        try:
            # 语法检查
            compile(code, "<skill>", "exec")
        except SyntaxError as e:
            return False, f"语法错误: {e}"

        # 必需元素检查
        checks = [
            ("SKILL_ID", "SKILL_ID"),
            ("SKILL_NAME", "SKILL_NAME"),
            ("def execute", "execute 函数"),
        ]
        for keyword, label in checks:
            if keyword not in code:
                return False, f"缺少必需元素: {label}"

        return True, "代码验证通过"

    def save_skill(self, skill_id: str, code: str, name: str) -> Tuple[bool, str]:
        """
        保存 Skill 到 skills/ 目录

        Returns:
            (success, message)
        """
        try:
            self._ensure_skills_dir()
            # 使用安全的文件名
            safe_name = re.sub(r'[^\w\-_]', '_', skill_id)
            filepath = SKILLS_DIR / f"{safe_name}.py"

            # 检查是否已存在
            if filepath.exists():
                return False, f"Skill 文件已存在: {filepath.name}（请使用不同的 ID）"

            filepath.write_text(code, encoding="utf-8")
            logger.info(f"[SkillBuilder] Skill 已保存: {name} → {filepath}")
            return True, f"Skill 已保存: {filepath.name}"
        except Exception as e:
            logger.error(f"[SkillBuilder] 保存失败: {e}")
            return False, f"保存失败: {e}"

    def generate_intermediate_skill(self, name: str, description: str,
                                     extra_info: str = "",
                                     triggers: str = "",
                                     skill_id: str = None) -> Dict[str, str]:
        """
        生成中级 Skill（SKILL.md + scripts/main.py）

        Args:
            triggers: 用户自定义触发词（逗号分隔），为空则自动提取

        Returns:
            dict: {"skill_md": str, "main_py": str, "skill_id": str, "name": str}
        """
        if not skill_id:
            skill_id = re.sub(r'[^\w\-_]', '_', name.lower())[:20] or f"skill_{uuid.uuid4().hex[:6]}"

        template = SKILL_CATEGORY_TEMPLATES["intermediate"]

        # 触发词：用户自定义优先，否则自动提取
        if triggers:
            trigger_list = [t.strip() for t in triggers.split(',') if t.strip()][:8]
        else:
            trigger_list = self._extract_triggers(name, description, template.get("triggers", []))
        trigger_str = ", ".join(trigger_list) if trigger_list else "根据描述自动匹配"

        skill_md = template["skill_md"].format(
            name=name,
            description=description,
            triggers=trigger_str,
            extra_info=extra_info or "（请在此补充使用说明）",
            skill_id=skill_id,
        )

        main_py = template["main_py"].format(
            name=name,
            skill_id=skill_id,
            date=datetime.now().strftime("%Y-%m-%d %H:%M"),
        )

        return {
            "skill_md": skill_md,
            "main_py": main_py,
            "skill_id": skill_id,
            "name": name,
        }

    def save_intermediate_skill(self, skill_id: str, name: str,
                                 skill_md: str, main_py: str) -> Tuple[bool, str]:
        """
        保存中级 Skill 到 data/skills/<skill_id>/ 目录

        Returns:
            (success, message)
        """
        try:
            # ★ 保存到 data/skills/（与 skills_manager 和 scripts_runner 一致）
            from src.core.skills_manager import SKILLS_DIR as DATA_SKILLS_DIR
            skill_dir = DATA_SKILLS_DIR / skill_id
            scripts_dir = skill_dir / "scripts"
            scripts_dir.mkdir(parents=True, exist_ok=True)

            # 检查是否已存在
            if (skill_dir / "SKILL.md").exists():
                return False, f"中级Skill 已存在: {skill_id}（请使用不同的名称）"

            (skill_dir / "SKILL.md").write_text(skill_md, encoding="utf-8")
            (scripts_dir / "main.py").write_text(main_py, encoding="utf-8")

            logger.info(f"[SkillBuilder] 中级Skill 已保存: {name} → {skill_dir}")
            return True, f"中级Skill 已保存到 data/skills/{skill_id}/"
        except Exception as e:
            logger.error(f"[SkillBuilder] 中级Skill 保存失败: {e}")
