/** 翻译：en 缺词回退中文，中文缺词回退 key 本身 */
export function t(key, params) {
  let s = key
  if (lang.value === 'en' && en[key]) s = en[key]
  else if (zh[key]) s = zh[key]
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  }
  return s
}

/** 切换语言：写 localStorage + 同步后端（B方案标签等后端输出跟随） */
export function setLang(l) {
  if (l !== 'zh' && l !== 'en') return
  lang.value = l
  try { localStorage.setItem(LANG_KEY, l) } catch (_) {}
  fetch('/api/settings/language', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ ui_lang: l === 'en' ? 'en_US' : 'zh_CN' }),
  }).catch(() => {})
}
